using System.Net;
using System.Net.Security;
using System.Net.Sockets;
using System.Security.Authentication;
using System.Security.Cryptography.X509Certificates;
using RdpSniffer.Core.Abstractions;
using RdpSniffer.Probes.CredSsp;
using Xunit;

namespace RdpSniffer.Tests;

/// <summary>
/// End-to-end loopback tests for the protocol-based (CredSSP/NLA) login client.
/// A minimal fake NLA RDP server (X.224 negotiation + TLS + Microsoft SSPI NTLM) runs on a random local port,
/// so the real wire format of the client is exercised: TSRequest framing, SPNEGO/NTLM challenge/authenticate,
/// and the success/rejection classification.
/// </summary>
public class CredSspLoginClientIntegrationTests
{
    private static readonly string TestPassword = "RdpSniffer-Integration-P@ss";

    [Fact]
    public async Task LegacyServerWithoutNla_ReturnsProtocolError()
    {
        var listener = new TcpListener(IPAddress.Loopback, 0);
        listener.Start();
        var port = ((IPEndPoint)listener.LocalEndpoint).Port;

        var server = Task.Run(() => RunLegacyServerAsync(listener));

        var client = new CredSspLoginClient();
        var result = await client.LoginAsync(BuildRequest(port), CancellationToken.None);

        Assert.False(result.Succeeded);
        Assert.Equal(MstscLoginFailureKind.ProtocolError, result.FailureKind);
        Assert.Contains("NLA", result.ErrorDescription, StringComparison.OrdinalIgnoreCase);

        await server;
    }

    [Fact]
    public async Task ServerAcceptsAfterAuthenticate_ReturnsSucceeded()
    {
        var (port, serverAccepted) = await RunNlaServerAndGetPortAsync(accept: true);

        var client = new CredSspLoginClient();
        var result = await client.LoginAsync(BuildRequest(port, password: TestPassword), CancellationToken.None);

        Assert.True(result.Succeeded, $"Expected success, got {result.FailureKind}: {result.ErrorDescription}");
        Assert.True(await serverAccepted, "The fake server should have received the client's authenticate message");
    }

    [Fact]
    public async Task ConnectionClosedAfterAuthenticate_ReturnsAuthenticationError()
    {
        var (port, serverAccepted) = await RunNlaServerAndGetPortAsync(accept: false);

        var client = new CredSspLoginClient();
        var result = await client.LoginAsync(BuildRequest(port, password: "definitely-not-the-password"), CancellationToken.None);

        Assert.False(result.Succeeded);
        Assert.Equal(MstscLoginFailureKind.AuthenticationError, result.FailureKind);
        Assert.True(await serverAccepted, "The fake server should have received the client's authenticate message");
    }

    private static MstscLoginRequest BuildRequest(int port, string? password = null)
        => new()
        {
            Host = "127.0.0.1",
            Port = port,
            UserName = Environment.UserName,
            Password = password ?? TestPassword,
            Timeout = TimeSpan.FromSeconds(10),
        };

    private static async Task<(int Port, Task<bool> ServerAccepted)> RunNlaServerAndGetPortAsync(bool accept)
    {
        var listener = new TcpListener(IPAddress.Loopback, 0);
        listener.Start();
        var port = ((IPEndPoint)listener.LocalEndpoint).Port;
        var accepted = RunNlaServerAsync(listener, accept);
        return (port, accepted);
    }

    private static async Task RunLegacyServerAsync(TcpListener listener)
    {
        using (listener)
        {
            using var tcp = await listener.AcceptTcpClientAsync();
            using var stream = tcp.GetStream();
            await ReadAtLeastAsync(stream, new byte[19], 4, CancellationToken.None);
            // X.224 connection confirm WITHOUT the RDP protocol-negotiation block (legacy security).
            await stream.WriteAsync(new byte[] { 0x03, 0x00, 0x00, 0x0B, 0x06, 0xD0, 0x00, 0x00, 0x12, 0x34, 0x00 }, CancellationToken.None);
            await stream.FlushAsync(CancellationToken.None);
        }
    }

    /// <summary>
    /// Runs a complete NLA server exchange and reports whether the client's authenticate message arrived:
    /// TCP → X.224 CC (with negotiation response, selectedProtocol=HYBRID) → TLS → TSRequest(negotiate)
    /// → TSRequest(challenge generated by real SSPI) → TSRequest(authenticate).
    /// The server challenge is produced by the Microsoft SSPI so the client's SPNEGO/NTLM framing is
    /// exercised against a spec-perfect opponent. After the authenticate:
    ///   accept=true  → the server "continues CredSSP" by sending a pubKeyAuth TSRequest (client → Succeeded);
    ///   accept=false → the server tears the connection down, like a real NLA server rejecting wrong
    ///                  credentials (client → AuthenticationError).
    /// </summary>
    private static async Task<bool> RunNlaServerAsync(TcpListener listener, bool accept)
    {
        using var cts = new CancellationTokenSource(TimeSpan.FromSeconds(30));
        using (listener)
        using (var tcp = await listener.AcceptTcpClientAsync(cts.Token))
        using (var stream = tcp.GetStream())
        {
            var cr = new byte[19];
            await ReadAtLeastAsync(stream, cr, cr.Length, cts.Token);

            // X.224 connection confirm + RDP negotiation response (selectedProtocol = 0x02 HYBRID).
            await stream.WriteAsync(new byte[]
            {
                0x03, 0x00, 0x00, 0x13, 0x0E, 0xD0, 0x00, 0x00, 0x12, 0x34, 0x00,
                0x02, 0x00, 0x08, 0x00, 0x02, 0x00, 0x00, 0x00,
            }, cts.Token);
            await stream.FlushAsync(cts.Token);

            using var ssl = new SslStream(stream, leaveInnerStreamOpen: true, (_, _, _, _) => true);
            var cert = CreateServerCertificate();
            using (cert)
            {
                await ssl.AuthenticateAsServerAsync(new SslServerAuthenticationOptions
                {
                    ServerCertificate = cert,
                    EnabledSslProtocols = SslProtocols.Tls12,
                }, cts.Token);
            }

            // 1) client NTLM Negotiate
            var negotiateFrame = await ReadNlFrameAsync(ssl, cts.Token);
            var negotiate = TsRequestCodec.Decode(negotiateFrame);
            if (negotiate.NegoTokens.Count == 0)
            {
                return false;
            }

            // 2) challenge — generated by the real SSPI with any credential (the server challenge itself
            // does not depend on the validated account).
            using var server = new NegotiateAuthentication(new NegotiateAuthenticationServerOptions
            {
                Credential = new NetworkCredential(Environment.UserName, TestPassword),
                Package = "Negotiate",
            });

            var challenge = server.GetOutgoingBlob(negotiate.NegoTokens[0], out var challengeStatus);
            if (challenge is null || challengeStatus != NegotiateAuthenticationStatusCode.ContinueNeeded)
            {
                return false;
            }

            await WriteNlFrameAsync(ssl, TsRequestCodec.EncodeWithNegoToken(challenge), cts.Token);

            // 3) client authenticate
            var authenticateFrame = await ReadNlFrameAsync(ssl, cts.Token);
            var authenticate = TsRequestCodec.Decode(authenticateFrame);
            if (authenticate.NegoTokens.Count == 0)
            {
                return false;
            }

            if (accept)
            {
                // A real NLA server continues the CredSSP exchange here (e.g. by sending its pubKeyAuth);
                // any data tells the client that the NTLM authentication was accepted.
                await WriteNlFrameAsync(ssl, BuildPubKeyAuthTsRequest(), cts.Token);
                return true;
            }

            // Rejection path: the server tears the connection down → the client must observe an EOF.
            return true;
        }
    }

    private static X509Certificate2 CreateServerCertificate()
    {
        using var rsa = System.Security.Cryptography.RSA.Create(2048);
        var request = new System.Security.Cryptography.X509Certificates.CertificateRequest(
            "CN=127.0.0.1",
            rsa,
            System.Security.Cryptography.HashAlgorithmName.SHA256,
            System.Security.Cryptography.RSASignaturePadding.Pkcs1);
        using var selfSigned = request.CreateSelfSigned(DateTimeOffset.UtcNow.AddDays(-1), DateTimeOffset.UtcNow.AddDays(1));
        return X509CertificateLoader.LoadPkcs12(selfSigned.Export(X509ContentType.Pfx), null);
    }

    private static byte[] BuildPubKeyAuthTsRequest()
    {
        // TSRequest ::= SEQUENCE { version [0] INTEGER 2, pubKeyAuth [3] OCTET STRING }
        var version = Tlv(0xA0, new byte[] { 0x02, 0x01, 0x02 });
        var pubKeyAuth = Tlv(0xA3, new byte[] { 0xDE, 0xAD, 0xBE, 0xEF, 0x01, 0x02 });
        return Tlv(0x30, Concat(version, pubKeyAuth));
    }

    private static async Task<byte[]> ReadNlFrameAsync(Stream stream, CancellationToken ct)
    {
        var header = new byte[2];
        await ReadAtLeastAsync(stream, header, 2, ct);
        var first = header[1];
        var lengthLength = (first & 0x80) == 0 ? 0 : first & 0x7F;
        var lengthBytes = new byte[lengthLength];
        if (lengthLength > 0)
        {
            await ReadAtLeastAsync(stream, lengthBytes, lengthLength, ct);
        }

        var contentLength = (first & 0x80) == 0 ? first : 0;
        if (lengthLength > 0)
        {
            contentLength = 0;
            foreach (var b in lengthBytes)
            {
                contentLength = (contentLength << 8) | b;
            }
        }

        var content = new byte[contentLength];
        await ReadAtLeastAsync(stream, content, contentLength, ct);

        var frame = new byte[2 + lengthLength + contentLength];
        header.CopyTo(frame, 0);
        lengthBytes.CopyTo(frame, 2);
        content.CopyTo(frame, 2 + lengthLength);
        return frame;
    }

    private static async Task WriteNlFrameAsync(Stream stream, byte[] frame, CancellationToken ct)
    {
        await stream.WriteAsync(frame, ct);
        await stream.FlushAsync(ct);
    }

    private static async Task<int> ReadAtLeastAsync(Stream stream, byte[] buffer, int minimum, CancellationToken ct)
    {
        var total = 0;
        while (total < minimum)
        {
            var read = await stream.ReadAsync(buffer.AsMemory(total), ct);
            if (read == 0)
            {
                break;
            }

            total += read;
        }

        return total;
    }

    private static byte[] Tlv(byte tag, byte[] content)
    {
        var result = new byte[2 + content.Length];
        result[0] = tag;
        result[1] = (byte)content.Length;
        content.CopyTo(result, 2);
        return result;
    }

    private static byte[] Concat(params byte[][] parts)
    {
        var result = new byte[parts.Sum(p => p.Length)];
        var offset = 0;
        foreach (var part in parts)
        {
            part.CopyTo(result, offset);
            offset += part.Length;
        }

        return result;
    }
}
